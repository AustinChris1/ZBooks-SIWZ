// Regenerates the published SIWZ domain-key test vectors.
//
// Run from the package root, after a build:
//   pnpm build && node scripts/gen-vectors.mjs
//
// Every value in the output is derived from the counting seed below, so the
// file is reproducible and contains no real key material.

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deriveSiwzDomainKey, signSiwzMessage, SiwzMessage } from "../dist/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, "..", "vectors", "siwz-domain-key-v1.json");

// The 64-byte BIP 39 seed position is filled with 0x00..0x3f. Chosen so the
// seed is obviously synthetic at a glance.
const seed = new Uint8Array(64);
for (let i = 0; i < seed.length; i++) seed[i] = i;

const specs = [
  { domain: "example.com", uri: "https://example.com/login", network: "mainnet",
    nonce: "abcdefgh12345678", issuedAt: "2026-10-20T00:00:00Z",
    statement: "Sign in to Example. This does not move funds." },
  { domain: "example.com", uri: "https://example.com/login", network: "mainnet",
    nonce: "ZZZZ0000aaaa1111", issuedAt: "2026-10-20T12:34:56Z",
    expirationTime: "2026-10-20T12:44:56Z" },
  { domain: "other.example", uri: "https://other.example/", network: "mainnet",
    nonce: "qrstuvwx87654321", issuedAt: "2026-10-20T00:00:00Z" },
  { domain: "localhost:3000", uri: "http://localhost:3000/", network: "testnet",
    nonce: "localdev12345678", issuedAt: "2026-10-20T00:00:00Z" },
  { domain: "example.com", uri: "https://example.com/login", network: "mainnet",
    nonce: "account1nonce123", issuedAt: "2026-10-20T00:00:00Z", account: 1 },
  { domain: "example.com", uri: "https://example.com/login", network: "mainnet",
    nonce: "account7nonce999", issuedAt: "2026-10-20T00:00:00Z", account: 7 },
];

const cases = specs.map(({ account = 0, ...s }) => {
  const key = deriveSiwzDomainKey(seed, s.domain, account);
  const message = new SiwzMessage({ ...s, address: key.identity }).toString();
  return {
    domain: s.domain,
    account,
    identity: key.identity,
    secretKeyHex: Buffer.from(key.secretKey).toString("hex"),
    publicKeyHex: Buffer.from(key.publicKey).toString("hex"),
    message,
    signatureBase64: signSiwzMessage(message, key.secretKey),
  };
});

const out = {
  spec: "SIWZ domain-key signatures v1",
  NOTICE:
    "These are PUBLISHED TEST VECTORS, not credentials. Every key below is " +
    "derived from the synthetic seed 0x000102...3f and is intended to be " +
    "public so wallet implementers can verify their derivation. Secret " +
    "scanners flag the hex and base64 fields as high-entropy strings; that is " +
    "expected and harmless. No real seed, key or token appears in this file.",
  note:
    "Generated by scripts/gen-vectors.mjs. Wallets should reproduce identity, " +
    "secretKeyHex and signatureBase64 exactly.",
  derivation: {
    root: 'BLAKE2b-256(seed, personal="SIWZ_Root_v1____")',
    secretKey:
      'BLAKE2b-256(BE32(account) || utf8(normalizedDomain), key=root, personal="SIWZ_Domain_v1__")',
    publicKey: "Ed25519 public key of secretKey",
    identity: 'bech32m("siwz", publicKey)',
    signedPayload: '"SIWZ-domain-key-v1:\\n" + message, signed with Ed25519',
  },
  seedBytes: 64,
  seedNote:
    "The 64-byte BIP 39 binary seed. Exactly this length is required. This " +
    "particular seed is the byte sequence 0x00 through 0x3f.",
  seedHex: Buffer.from(seed).toString("hex"),
  cases,
};

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${cases.length} cases to ${outPath}`);
